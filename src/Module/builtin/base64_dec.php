<?php
// 自制 base64 解码：替换原生 base64_decode。VM 兼容写法（无闭包/无类型/用 []）。
//
// 两条性能红线（踩过，别再犯）：
//  1. 逐字符取值必须用【下标直取】`$s[$i]`，绝不能写 substr($s,$i,1)。模块内
//     substr 会被传递式链接成 __mod_substr，其一般路径首步 strlen 是整串扫描
//     （O(n)），每字符调 4 次 → 整串解码退化成 O(n²)：实测 6KB 要 8.2s，100KB
//     要数十分钟，表现就是"混淆产物运行挂死"。
//  2. 字符 → 6bit 值的查表用【一次建好的映射表】（static 缓存），不要每字符
//     strpos() 在 64 字符表里线性找（那是每字符 64 次比较的 VM 循环）。
function __b64_dec($__s)
{
    static $__m = null;
    if ($__m === null) {
        $__m = [];
        $__t = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
        $__j = 0;
        $__tn = strlen($__t);
        while ($__j < $__tn) {
            $__m[$__t[$__j]] = $__j;
            $__j = $__j + 1;
        }
    }
    $__len = strlen($__s);
    $__out = '';
    $__i = 0;
    // 主循环：每次吃满 4 字符（保证不越界，故可零额外函数调用直接下标取）
    while ($__i + 3 < $__len) {
        $__c0 = isset($__m[$__s[$__i]]) ? $__m[$__s[$__i]] : -1;
        $__c1 = isset($__m[$__s[$__i + 1]]) ? $__m[$__s[$__i + 1]] : -1;
        $__c2 = isset($__m[$__s[$__i + 2]]) ? $__m[$__s[$__i + 2]] : -1;
        $__c3 = isset($__m[$__s[$__i + 3]]) ? $__m[$__s[$__i + 3]] : -1;
        $__i = $__i + 4;
        $__tr = (max($__c0, 0) << 18) + (max($__c1, 0) << 12) + (max($__c2, 0) << 6) + max($__c3, 0);
        $__out .= chr(($__tr >> 16) & 255);
        if ($__c2 >= 0) {
            $__out .= chr(($__tr >> 8) & 255);
        }
        if ($__c3 >= 0) {
            $__out .= chr($__tr & 255);
        }
    }
    // 尾组：输入长度不是 4 的倍数时（含空白/换行的宽松输入）补齐处理
    if ($__i < $__len) {
        $__p = [0, 0, 0, 0];
        $__k = 0;
        while ($__i < $__len && $__k < 4) {
            $__p[$__k] = isset($__m[$__s[$__i]]) ? $__m[$__s[$__i]] : -1;
            $__i = $__i + 1;
            $__k = $__k + 1;
        }
        $__tr = (max($__p[0], 0) << 18) + (max($__p[1], 0) << 12) + (max($__p[2], 0) << 6) + max($__p[3], 0);
        $__out .= chr(($__tr >> 16) & 255);
        if ($__k > 2 && $__p[2] >= 0) {
            $__out .= chr(($__tr >> 8) & 255);
        }
        if ($__k > 3 && $__p[3] >= 0) {
            $__out .= chr($__tr & 255);
        }
    }
    return $__out;
}

function __b64_i($__t, $__ch)
{
    // 越界读在 VM 下返回 null（原生为 ''）；两种形态都按"非表字符"处理
    if ($__ch === null || $__ch === '') {
        return -1;
    }
    $__p = strpos($__t, (string) $__ch);
    return ($__p === false) ? -1 : $__p;
}
